) AS g(name, ord)
WHERE NOT EXISTS (
    SELECT 1 FROM "Governorate" x
    WHERE lower(x."name") = lower(g.name)
       OR (lower(g.name) = 'matrouh' AND lower(x."name") = 'matruh')
);

