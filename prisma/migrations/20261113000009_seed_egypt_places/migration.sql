-- One-time import of Egypt's 27 governorates and their main cities / areas.
--  * Safe to run on a store that already has some of them: anything that already exists
--    (matched ignoring upper/lower case) is left exactly as it is, including prices and Active settings.
--  * NEW governorates are added HIDDEN (not Active) with shipping price 0, so nothing becomes
--    "free shipping" by accident. Set a price and tick Active in Admin > Shipping (or use the bulk box there).
--  * New cities are added to their governorate with no price (shipping is priced per governorate).

INSERT INTO "Governorate" ("id", "name", "isActive", "sortOrder", "shippingPrice", "updatedAt")
